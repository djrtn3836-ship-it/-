def sanitize_name(name: str) -> str:
    if not name:
        return ""
    name = re.sub(r'<[^>]+>', '', name)
    return name.strip()


def is_valid_stock_code(code: str) -> bool:
    return bool(STOCK_CODE_PATTERN.match(str(code).strip()))


