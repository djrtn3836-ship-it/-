# create_universe_csv.py - KRX CSV 파싱 + Fallback
import csv
import requests
import pandas as pd
from io import StringIO

def download_krx_universe():
    """KRX에서 종목 리스트 CSV를 다운로드하여 파싱"""
    url = "https://kind.krx.co.kr/corpgeneral/corpList.do?method=download&searchType=13"
    response = requests.get(url, timeout=10)
    response.encoding = 'cp949'
    
    # csv.reader로 안전하게 파싱
    reader = csv.reader(StringIO(response.text), delimiter=',', quotechar='"')
    rows = list(reader)
    
    if not rows:
        return None
    
    # 헤더 찾기 (종목코드, 회사명 컬럼 위치)
    header = rows[0]
    code_idx = None
    name_idx = None
    for i, col in enumerate(header):
        if '종목코드' in col:
            code_idx = i
        elif '회사명' in col:
            name_idx = i
    
    if code_idx is None or name_idx is None:
        # 컬럼명이 다를 경우 (일부 버전)
        code_idx = 0
        name_idx = 1
    
    universe = {}
    for row in rows[1:]:
        if len(row) <= max(code_idx, name_idx):
            continue
        code = row[code_idx].strip()
        name = row[name_idx].strip()
        if code and name:
            code = code.zfill(6)
            universe[code] = name
    
    return universe

